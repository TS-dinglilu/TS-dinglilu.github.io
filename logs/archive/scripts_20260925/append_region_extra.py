changed = []
for cat, block in BLOCKS.items():
    path = os.path.join(CONTENT, cat + ".html")
    with io.open(path, "r", encoding="utf-8") as f:
        html = f.read()
    if block in html:
        print("[SKIP] %s 已追加过" % cat)
        continue
    assert ANCHOR in html, "[FATAL] %s 找不到插入锚点" % cat
    html = html.replace(ANCHOR, block + ANCHOR, 1)
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(html)
    changed.append((cat, len(html)))
    print("[OK] %s -> %d chars" % (cat, len(html)))

assert len(changed) == 5, "预期改 5 份，实际 %d 份" % len(changed)
